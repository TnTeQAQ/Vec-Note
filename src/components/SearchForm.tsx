import { useState } from 'react';
import { embed } from '../lib/embed';
import { searchNotes, type SearchResult } from '../lib/api';
import Button from './Button';
import './SearchForm.css';

export type SearchOutcome = {
  query: string;
  /** 查询向量（分页翻页时复用同一向量，保证排序一致、无重复/跳漏） */
  vector: number[];
  results: SearchResult[];
  total: number;
  hasMore: boolean;
};

/**
 * 搜索表单：查询词本地向量化后交 Worker 密封召回第一页。
 * 加载中按钮宽度不变，文字隐去、中央显示旋转加载图标。
 */
export default function SearchForm({ onResults }: { onResults: (o: SearchOutcome | null) => void }) {
  const [query, setQuery] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function handleSearch(e: React.FormEvent) {
    e.preventDefault();
    if (loading) return; // 防重复提交
    setError(null);
    const q = query.trim();
    if (!q) return;

    const vector = embed(q);
    if (!vector) {
      setError('查询词规范化后为空');
      return;
    }

    setLoading(true);
    try {
      const { results, total, hasMore } = await searchNotes(vector, 0);
      onResults({ query: q, vector, results, total, hasMore });
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err));
    } finally {
      setLoading(false);
    }
  }

  return (
    <form className="search-form" onSubmit={handleSearch}>
      <div className="search-form__row">
        <input
          className="field search-form__input"
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          placeholder="请输入搜索词"
          autoComplete="off"
        />
        <Button type="submit" variant="solid" size="md" disabled={!query.trim()}>
          {/* 加载时文字占位隐藏（保持按钮宽度），中央显示加载图标 */}
          <span
            className={loading ? 'search-form__label search-form__label--hidden' : 'search-form__label'}
          >
            搜索
          </span>
          {loading && (
            <svg
              className="search-form__spinner"
              viewBox="0 0 1024 1024"
              xmlns="http://www.w3.org/2000/svg"
              aria-hidden="true"
            >
              <path d="M597.466453 76.356267C597.466453 118.510933 563.264853 152.712533 521.110187 152.712533 478.95552 152.712533 444.75392 118.510933 444.75392 76.356267 444.75392 34.2016 478.95552 0 521.110187 0 563.264853 0 597.466453 34.2016 597.466453 76.356267" />
              <path d="M403.060053 118.227627C403.060053 157.924693 370.87232 190.112427 331.175253 190.112427 291.478187 190.112427 259.324587 157.924693 259.324587 118.227627 259.324587 78.53056 291.478187 46.342827 331.175253 46.342827 370.87232 46.342827 403.060053 78.53056 403.060053 118.227627" />
              <path d="M248.49408 231.297707C248.49408 268.50304 218.320213 298.676907 181.11488 298.676907 143.875413 298.676907 113.701547 268.50304 113.701547 231.297707 113.701547 194.092373 143.875413 163.918507 181.11488 163.918507 218.320213 163.918507 248.49408 194.092373 248.49408 231.297707" />
              <path d="M152.579413 396.752213C152.579413 431.499947 124.419413 459.659947 89.67168 459.659947 54.923947 459.659947 26.763947 431.499947 26.763947 396.752213 26.763947 362.00448 54.923947 333.84448 89.67168 333.84448 124.419413 333.84448 152.579413 362.00448 152.579413 396.752213" />
              <path d="M133.90848 593.435307C133.90848 625.691307 107.762347 651.871573 75.472213 651.871573 43.216213 651.871573 17.07008 625.691307 17.07008 593.435307 17.07008 561.179307 43.216213 534.99904 75.472213 534.99904 107.762347 534.99904 133.90848 561.179307 133.90848 593.435307" />
              <path d="M197.116587 772.16768C197.116587 801.96608 172.98432 826.098347 143.18592 826.098347 113.38752 826.098347 89.255253 801.96608 89.255253 772.16768 89.255253 742.36928 113.38752 718.237013 143.18592 718.237013 172.98432 718.237013 197.116587 742.36928 197.116587 772.16768" />
              <path d="M325.256533 904.789333C325.256533 932.096 303.104 954.248533 275.797333 954.248533 248.490667 954.248533 226.338133 932.096 226.338133 904.789333 226.338133 877.482667 248.490667 855.330133 275.797333 855.330133 303.104 855.330133 325.256533 877.482667 325.256533 904.789333" />
              <path d="M499.503787 972.485973C499.503787 997.33504 479.36512 1017.439573 454.550187 1017.439573 429.70112 1017.439573 409.562453 997.33504 409.562453 972.485973 409.562453 947.636907 429.70112 927.532373 454.550187 927.532373 479.36512 927.532373 499.503787 947.636907 499.503787 972.485973" />
              <path d="M691.705173 958.296747C691.705173 980.65408 673.580373 998.77888 651.22304 998.77888 628.865707 998.77888 610.740907 980.65408 610.740907 958.296747 610.740907 935.939413 628.865707 917.814613 651.22304 917.814613 673.580373 917.814613 691.705173 935.939413 691.705173 958.296747" />
              <path d="M852.67456 866.8672C852.67456 886.7328 836.563627 902.877867 816.663893 902.877867 796.798293 902.877867 780.68736 886.7328 780.68736 866.8672 780.68736 847.0016 796.798293 830.856533 816.663893 830.856533 836.563627 830.856533 852.67456 847.0016 852.67456 866.8672" />
              <path d="M961.25952 716.786347C961.25952 734.194347 947.162453 748.291413 929.754453 748.291413 912.346453 748.291413 898.215253 734.194347 898.215253 716.786347 898.215253 699.378347 912.346453 685.28128 929.754453 685.28128 947.162453 685.28128 961.25952 699.378347 961.25952 716.786347" />
              <path d="M998.64576 526.861653C998.64576 541.77792 986.528427 553.895253 971.61216 553.895253 956.695893 553.895253 944.57856 541.77792 944.57856 526.861653 944.57856 511.945387 956.695893 499.828053 971.61216 499.828053 986.528427 499.828053 998.64576 511.945387 998.64576 526.861653" />
            </svg>
          )}
        </Button>
      </div>
      {error && <p className="search-form__error">{error}</p>}
    </form>
  );
}
